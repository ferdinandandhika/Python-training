# Solusi function sederhana


def sapa(nama):  # Definisikan fungsi yang menerima nama dan menyusun teks salam.
    return f"Halo, {nama}!"  # Kembalikan salam yang menyisipkan nama dari argumen fungsi.


hasil = sapa("Budi")  # Panggil fungsi sapa dengan nama Budi dan simpan teks salamnya.
print(hasil)  # Tampilkan salam yang dikembalikan oleh fungsi.
